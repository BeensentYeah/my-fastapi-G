-- =====================================================================
-- Item API: Supabase schema  (run FIRST, in Supabase > SQL Editor)
--
-- WARNING: this drops the earlier test tables public.items / public.categories
-- and recreates them. Only run it on a project that holds nothing you want to keep.
-- =====================================================================

drop table if exists public.items cascade;
drop table if exists public.categories cascade;

-- One category has many items (one-to-many).
create table public.categories (
  id   text primary key check (id ~ '^[a-z]+$'),
  name text not null unique check (length(trim(name)) > 0)
);

create table public.items (
  id          integer generated by default as identity primary key,
  name        text    not null check (length(trim(name)) > 0),
  price       integer not null check (price >= 0),
  sell_price  integer not null check (sell_price >= 0),
  category_id text    not null references public.categories (id)
                              on update cascade on delete restrict,
  image       text    not null check (length(trim(image)) > 0),
  description text    check (description is null or length(trim(description)) > 0),
  attack_damage      double precision not null default 0 check (attack_damage >= 0),
  ability_power      double precision not null default 0 check (ability_power >= 0),
  attack_speed       double precision not null default 0 check (attack_speed >= 0),
  health             double precision not null default 0 check (health >= 0),
  mana               double precision not null default 0 check (mana >= 0),
  armor              double precision not null default 0 check (armor >= 0),
  magic_resist       double precision not null default 0 check (magic_resist >= 0),
  crit_chance        double precision not null default 0 check (crit_chance >= 0),
  ability_haste      double precision not null default 0 check (ability_haste >= 0),
  movement_speed     double precision not null default 0 check (movement_speed >= 0),
  life_steal         double precision not null default 0 check (life_steal >= 0),
  armor_penetration  double precision not null default 0 check (armor_penetration >= 0),
  magic_penetration  double precision not null default 0 check (magic_penetration >= 0),
  tenacity           double precision not null default 0 check (tenacity >= 0),
  omnivamp           double precision not null default 0 check (omnivamp >= 0),
  constraint items_sell_price_lte_price check (sell_price <= price)
);

-- Item names are unique, ignoring upper/lower case (a duplicate name returns 409 in the API).
create unique index items_name_unique on public.items (lower(name));
-- Speeds up "items in category X" and the join to categories.
create index items_category_id_idx on public.items (category_id);

-- ---------------------------------------------------------------------
-- Security: Row Level Security.
-- The public (publishable) key may only READ. There is no insert/update/delete
-- policy and no write privilege, so writes are possible only with the secret key,
-- which must stay on the server (Vercel environment variable).
-- ---------------------------------------------------------------------
alter table public.categories enable row level security;
alter table public.items      enable row level security;

create policy "categories are publicly readable"
  on public.categories for select to anon, authenticated using (true);
create policy "items are publicly readable"
  on public.items for select to anon, authenticated using (true);

-- Least privilege: start from nothing, then grant only what is needed.
revoke all on public.categories, public.items from anon, authenticated;
grant select on public.categories, public.items to anon, authenticated;
grant all    on public.categories, public.items to service_role;
grant usage, select on sequence public.items_id_seq to service_role;



